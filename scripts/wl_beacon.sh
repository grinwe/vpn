#!/usr/bin/env bash
# Проверка «проходит ли наш адрес при отключённом мобильном интернете».
#
# Зачем. В режиме белых списков оператор пропускает трафик только на разрешённые
# IP-префиксы. Три наших адреса лежат в таких префиксах по публичному скан-списку —
# но список шумный (docs/operations/whitelist_counters.md §3.1), и единственная
# настоящая проверка — открыть адрес с мобильной SIM в затронутом регионе.
#
# Как работает. Человеку даются ссылки С УНИКАЛЬНЫМ ПУТЁМ. Он их открывает —
# запрос попадает в nginx-лог, и мы видим факт захода вместе с адресом источника.
# Пересказывать ничего не нужно, «мне кажется, открылось» не участвует.
#
# ВАЖНО для того, кто проверяет:
#   * VPN должен быть ВЫКЛЮЧЕН — иначе проверяется туннель, а не адрес;
#   * только мобильный интернет, не Wi-Fi (белые списки живут на сотовой сети);
#   * ссылки открываются ПО IP, потому что DNS в этом режиме не работает
#     (UDP 53 не проходит) — предупреждение браузера про сертификат ожидаемо,
#     его надо принять: нам важен сам факт соединения.
#
#   ./scripts/wl_beacon.sh links megafon-yaroslavl   # выдать ссылки
#   ./scripts/wl_beacon.sh collect megafon-yaroslavl # собрать результат
#
# Маяк с логами есть только на саб-зеркале (nl-web). Для двух других адресов
# результат снимается со слов: открылась любая страница (пусть даже ошибка
# сервера) = адрес прошёл; бесконечная загрузка = не прошёл.
set -euo pipefail

# IP, а не домены: DNS в whitelist-режиме недоступен.
MIRROR_IP="194.76.146.166"   # nl-web, саб-зеркало grwr.ink — 194.76.144.0/22
TURKEY_IP="185.235.243.24"   # ufo-tr-01 — 185.235.243.0/24
VDSINA_IP="88.218.61.170"    # vsin-ru-01 — 88.218.32.0/19

INV="$(dirname "$0")/../infra/ansible/inventories/prod/hosts.yml"
VAULT="${VAULT_PASS_FILE:-$HOME/.vpn_vault_pass}"

usage() { sed -n '2,30p' "$0"; exit 1; }
[ $# -ge 2 ] || usage
cmd="$1"; label="$2"
mark="wl-$label"

case "$cmd" in
  links)
    cat <<EOF
Проверка белых списков, метка «$label».

Открыть с телефона, ВЫКЛЮЧИВ VPN, на мобильном интернете (не Wi-Fi):

  1) https://$MIRROR_IP/$mark-1
  2) https://$TURKEY_IP/$mark-2
  3) https://$VDSINA_IP/$mark-3

Браузер ругнётся на сертификат — это нормально, надо продолжить.
Для каждой записать: открылась ЛЮБАЯ страница (пусть ошибка) или крутилось
до бесконечности. Заодно — какой оператор и город.

Первая ссылка проверяется автоматически:
  ./scripts/wl_beacon.sh collect $label
EOF
    ;;
  collect)
    echo "Ищу заходы с меткой «$mark» в логах саб-зеркала…"
    ansible nl-web -i "$INV" --vault-password-file "$VAULT" -m shell \
      -a "grep '$mark' /var/log/nginx/access.log | tail -20" 2>/dev/null \
      | grep -vE "WARNING|interpreter|docs.ansible" || true
    cat <<'EOF'

Как читать: строка с запросом = адрес ПРОШЁЛ (соединение дошло до нас).
Адрес слева — выходной IP оператора, по нему можно определить сеть.
Пусто = либо не открывали, либо адрес не прошёл; различить может только тот,
кто проверял.
EOF
    ;;
  *) usage ;;
esac
